"""Unified language definition + source enumeration rules (spec §6.2, §6.3).

Before this module the suffix sets were duplicated in at least four places and
had drifted apart:

* ``tools/source_evidence.DEFAULT_SOURCE_GLOBS``
* ``tools/project_profile._source_file_count``
* ``orchestrator/stages.run_s1`` (``_src_exts``)
* ``analysis`` (this package)

Every one of them now derives from :data:`LANGUAGE_SUFFIXES` here, so a new
language is added once.

Ambiguous suffixes
------------------
``.h`` is declared by both ``c`` and ``objective-c`` in the spec.  Resolution is
*first declaration wins* (see :func:`suffix_owner_language`), so ``.h`` maps to
``c`` -- the C/C++ header reading, which is the only defensible default for a
suffix whose contents are overwhelmingly C preprocessor + prototypes.  An
Objective-C header is still enumerated (the suffix is in the map); only its
*label* is conservative.  Override with :func:`set_ambiguous_suffix_owner` when a
target genuinely is Objective-C-dominant.

Enumeration contract (spec §18 Phase 1)
---------------------------------------
Exclusion is **never silent**.  :func:`scan_tree` does not descend into an
excluded directory, but it returns one :class:`ExcludedDir` record per excluded
directory carrying the file count inside it, so the coverage report can show what
was dropped and a reviewer can catch an over-broad exclusion (e.g. a project
whose real source lives under ``target/``).
"""

